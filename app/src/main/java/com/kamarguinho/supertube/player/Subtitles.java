package com.kamarguinho.supertube.player;

import android.app.Activity;
import android.content.Context;
import android.graphics.Color;
import android.graphics.Typeface;

import androidx.annotation.Nullable;

import com.google.android.material.dialog.MaterialAlertDialogBuilder;
import com.kamarguinho.supertube.R;

import com.google.android.exoplayer2.C;
import com.google.android.exoplayer2.ExoPlayer;
import com.google.android.exoplayer2.ui.CaptionStyleCompat;
import com.google.android.exoplayer2.ui.SubtitleView;
import com.google.android.exoplayer2.util.MimeTypes;

import org.schabi.newpipe.extractor.stream.StreamInfo;
import org.schabi.newpipe.extractor.stream.SubtitlesStream;

import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;

/**
 * Legendas como no YouTube: as legendas do vídeo (inclusive as geradas automaticamente
 * a partir da fala) e a tradução automática para português feita pelo próprio YouTube.
 */
public final class Subtitles {

    /** Uma opção do menu de legendas. */
    public static final class Option {
        public final String label;
        public final String url;
        public final String mimeType;
        /** Idioma (ex.: "pt", "en"). */
        public final String language;
        public final boolean autoGenerated;
        public final boolean translated;

        Option(final String label, final String url, final String mimeType,
               final String language, final boolean autoGenerated, final boolean translated) {
            this.label = label;
            this.url = url;
            this.mimeType = mimeType;
            this.language = language;
            this.autoGenerated = autoGenerated;
            this.translated = translated;
        }
    }

    /** Escolhas guardadas: desligado, português (com tradução), inglês, ou um idioma. */
    public static final String MODE_OFF = "off";
    public static final String MODE_PT = "pt";
    public static final String MODE_EN = "en";

    private static final String PREFS = "subtitles";
    private static final String KEY_MODE = "mode";
    

    private Subtitles() {
    }

    public static String mode(final Context context) {
        return context.getSharedPreferences(PREFS, Context.MODE_PRIVATE)
                .getString(KEY_MODE, MODE_OFF);
    }

    public static void setMode(final Context context, final String mode) {
        context.getSharedPreferences(PREFS, Context.MODE_PRIVATE).edit()
                .putString(KEY_MODE, mode).apply();
    }

    /** Todas as legendas do vídeo, mais a tradução automática para português. */
    public static List<Option> options(final StreamInfo info) {
        final Map<String, Option> byKey = new LinkedHashMap<>();
        SubtitlesStream translationBase = null;

        for (final SubtitlesStream s : info.getSubtitles()) {
            if (!s.isUrl()) {
                continue;
            }
            final String lang = baseLanguage(s.getLanguageTag());
            final String key = lang + (s.isAutoGenerated() ? ":auto" : "");
            if (byKey.containsKey(key)) {
                continue;
            }
            String label = languageName(s.getLanguageTag());
            if (s.isAutoGenerated()) {
                label += " (" + com.kamarguinho.supertube.util.Lang.t("gerada automaticamente") + ")";
            }
            byKey.put(key, new Option(label, asVtt(s.getContent()), MimeTypes.TEXT_VTT, lang,
                    s.isAutoGenerated(), false));

            // Base da tradução: de preferência uma legenda feita por pessoa, senão a automática
            if (translationBase == null
                    || (translationBase.isAutoGenerated() && !s.isAutoGenerated())) {
                translationBase = s;
            }
        }

        final List<Option> out = new ArrayList<>(byKey.values());
        // Tradução automática para o idioma do app (português, ou inglês se o app estiver em inglês)
        final String target = com.kamarguinho.supertube.util.Lang.english() ? "en" : "pt";
        final boolean hasReal = byKey.containsKey(target);
        if (translationBase != null && !hasReal
                && !target.equals(baseLanguage(translationBase.getLanguageTag()))) {
            out.add(0, new Option(com.kamarguinho.supertube.util.Lang.t(target.equals("en") ? "Inglês (tradução automática)"
                    : "Português (tradução automática)"),
                    asVtt(translationBase.getContent()) + "&tlang=" + target, MimeTypes.TEXT_VTT,
                    target, true, true));
        }
        return out;
    }

    /** A legenda que deve ser usada neste vídeo, de acordo com a escolha salva. */
    @Nullable
    public static Option pick(final StreamInfo info, final String mode) {
        if (MODE_OFF.equals(mode)) {
            return null;
        }
        final List<Option> options = options(info);
        Option best = null;
        for (final Option o : options) {
            if (!o.language.equals(mode)) {
                continue;
            }
            // Prefere: feita por pessoa > automática > traduzida
            if (best == null || score(o) > score(best)) {
                best = o;
            }
        }
        return best;
    }

    private static int score(final Option o) {
        return o.translated ? 0 : (o.autoGenerated ? 1 : 2);
    }

    /** Estilo parecido com o do YouTube: letra branca com fundo preto translúcido. */
    public static void applyStyle(@Nullable final SubtitleView view, final float scale) {
        if (view == null) {
            return;
        }
        view.setStyle(new CaptionStyleCompat(Color.WHITE, 0xBF080808, Color.TRANSPARENT,
                CaptionStyleCompat.EDGE_TYPE_NONE, Color.BLACK,
                Typeface.create(Typeface.SANS_SERIF, Typeface.NORMAL)));
        view.setFractionalTextSize(SubtitleView.DEFAULT_TEXT_SIZE_FRACTION * scale);
        view.setApplyEmbeddedStyles(false);
        view.setApplyEmbeddedFontSizes(false);
    }

    /** O extrator entrega TTML; pedimos WebVTT, que o player lê melhor. */
    private static String asVtt(final String url) {
        if (url.contains("fmt=")) {
            return url.replaceAll("fmt=[^&]*", "fmt=vtt");
        }
        return url + "&fmt=vtt";
    }

    private static String baseLanguage(final String tag) {
        if (tag == null || tag.isEmpty()) {
            return "und";
        }
        final int dash = tag.indexOf('-');
        return (dash > 0 ? tag.substring(0, dash) : tag).toLowerCase(Locale.ROOT);
    }

    private static String languageName(final String tag) {
        final Locale locale = Locale.forLanguageTag(tag);
        String name = locale.getDisplayName(com.kamarguinho.supertube.util.Lang.locale());
        if (name == null || name.isEmpty()) {
            name = tag;
        }
        return name.substring(0, 1).toUpperCase(com.kamarguinho.supertube.util.Lang.locale()) + name.substring(1);
    }

    /** Liga/desliga a faixa de legenda no player. */
    public static void select(final ExoPlayer player, @Nullable final Option option) {
        player.setTrackSelectionParameters(player.getTrackSelectionParameters().buildUpon()
                .setTrackTypeDisabled(C.TRACK_TYPE_TEXT, option == null)
                .setPreferredTextLanguage(option != null ? option.language : null)
                .build());
    }

    public interface OnChoice {
        /** {@code option} é null quando a pessoa escolhe "Desativadas". */
        void onChoice(@Nullable Option option);
    }

    /** Menu de legendas (funciona com toque e com controle remoto). */
    public static void showMenu(final Activity activity, final StreamInfo info,
                                @Nullable final Option current, final OnChoice listener) {
        final List<Option> options = options(info);
        if (options.isEmpty()) {
            new MaterialAlertDialogBuilder(activity)
                    .setTitle(R.string.subtitles)
                    .setMessage(R.string.subtitles_none)
                    .setPositiveButton(android.R.string.ok, null)
                    .show();
            return;
        }
        final String[] labels = new String[options.size() + 1];
        labels[0] = activity.getString(R.string.subtitles_off);
        int checked = 0;
        for (int i = 0; i < options.size(); i++) {
            labels[i + 1] = options.get(i).label;
            if (current != null && current.url.equals(options.get(i).url)) {
                checked = i + 1;
            }
        }
        new MaterialAlertDialogBuilder(activity)
                .setTitle(R.string.subtitles)
                .setSingleChoiceItems(labels, checked, (dialog, which) -> {
                    dialog.dismiss();
                    final Option chosen = which == 0 ? null : options.get(which - 1);
                    setMode(activity, chosen == null ? MODE_OFF : chosen.language);
                    listener.onChoice(chosen);
                })
                .setNegativeButton(android.R.string.cancel, null)
                .show();
    }
}
